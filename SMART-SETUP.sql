create or replace function public.oc_set_team_member(p_user_id uuid,p_role text) returns void
language plpgsql security definer set search_path='' as $$
begin
 if not public.oc_has_role(array['admin']) then raise exception 'Administrator access required' using errcode='42501';end if;
 if p_role not in ('admin','sales','product_editor') then raise exception 'Invalid role' using errcode='22023';end if;
 if not exists(select 1 from auth.users where id=p_user_id) then raise exception 'Create this user in Supabase Auth first' using errcode='22023';end if;
 perform 1 from public.admin_users for update;
 if exists(select 1 from public.admin_users where user_id=p_user_id and role='admin') and p_role<>'admin' and (select count(*) from public.admin_users where role='admin')<=1 then
  raise exception 'At least one administrator must remain' using errcode='22023';
