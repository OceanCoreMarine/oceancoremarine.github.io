create or replace function public.oc_save_quotation(p_id bigint,p_header jsonb,p_items jsonb,p_token uuid) returns jsonb language plpgsql security definer set search_path='' as $$
declare q public.quotations%rowtype;totals jsonb;line jsonb;num text;quote_id bigint;customer bigint;qd date;vd date;product_id bigint;
begin
 if not public.oc_has_role(array['admin','sales']) then raise exception 'Sales access required' using errcode='42501';end if;
 if p_token is null or jsonb_typeof(p_header) is distinct from 'object' then raise exception 'Invalid quotation' using errcode='22023';end if;
 perform pg_advisory_xact_lock(hashtextextended('quotation:'||p_token::text,0));
 if p_id is null then
  select * into q from public.quotations where client_token=p_token;
  if found then return jsonb_build_object('id',q.id,'number',q.quotation_number);end if;
 else
  select * into q from public.quotations where id=p_id for update;
  if not found then raise exception 'Quotation not found' using errcode='22023';end if;
  if coalesce((p_header->>'revision')::integer,0)<>q.revision then raise exception 'Quotation changed. Refresh before saving.' using errcode='40001';end if;
  if exists(select 1 from public.invoices where quotation_id=p_id and document_status<>'Cancelled') then raise exception 'Quotation already invoiced; create a new quotation for changed items' using errcode='22023';end if;
 end if;
 customer:=(p_header->>'customer_id')::bigint;
 if not exists(select 1 from public.customers where id=customer) then raise exception 'Select a customer' using errcode='22023';end if;
 qd:=coalesce(nullif(p_header->>'quotation_date','')::date,current_date);vd:=coalesce(nullif(p_header->>'valid_until','')::date,qd+15);
 if vd<qd then raise exception 'Valid-until date cannot precede quotation date' using errcode='22023';end if;
 totals:=public.oc_billing_totals(p_items,coalesce((p_header->>'other_charges')::numeric,0),coalesce((p_header->>'vat_rate')::numeric,5));
 if p_id is null then
  num:=public.next_quotation_number();
  insert into public.quotations(quotation_number,customer_id,quotation_date,valid_until,subtotal,discount,other_charges,vat_rate,vat_amount,grand_total,payment_type,delivery_terms,notes,created_by,client_token)
  values(num,customer,qd,vd,(totals->>'subtotal')::numeric,(totals->>'discount')::numeric,(totals->>'other_charges')::numeric,(totals->>'vat_rate')::numeric,(totals->>'vat_amount')::numeric,(totals->>'grand_total')::numeric,left(p_header->>'payment_type',200),left(p_header->>'delivery_terms',500),left(p_header->>'notes',10000),auth.uid(),p_token) returning id into quote_id;
 else
  quote_id:=p_id;num:=q.quotation_number;
  update public.quotations set customer_id=customer,quotation_date=qd,valid_until=vd,subtotal=(totals->>'subtotal')::numeric,discount=(totals->>'discount')::numeric,other_charges=(totals->>'other_charges')::numeric,vat_rate=(totals->>'vat_rate')::numeric,vat_amount=(totals->>'vat_amount')::numeric,grand_total=(totals->>'grand_total')::numeric,payment_type=left(p_header->>'payment_type',200),delivery_terms=left(p_header->>'delivery_terms',500),notes=left(p_header->>'notes',10000),revision=q.revision+1 where id=quote_id;
  delete from public.quotation_items where quotation_id=quote_id;
 end if;
 for line in select value from jsonb_array_elements(p_items) loop
  product_id:=nullif(line->>'product_id','')::bigint;
  if product_id is not null and not exists(select 1 from public.products where id=product_id) then raise exception 'Product no longer exists' using errcode='22023';end if;
  insert into public.quotation_items(quotation_id,product_id,product_name,part_number,brand_name,quantity,unit_price,discount,line_total)
  values(quote_id,product_id,line->>'product_name',line->>'part_number',line->>'brand_name',(line->>'quantity')::numeric,(line->>'unit_price')::numeric,coalesce((line->>'discount')::numeric,0),round((line->>'quantity')::numeric*(line->>'unit_price')::numeric,2)-coalesce((line->>'discount')::numeric,0));
 end loop;
 insert into public.smart_audit(entity,record_id,action,details,created_by) values('quotation',quote_id::text,'saved',totals,auth.uid());
 return jsonb_build_object('id',quote_id,'number',num);
end $$;
