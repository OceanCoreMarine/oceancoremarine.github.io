create or replace function public.oc_save_inventory(p_product_id bigint,p_values jsonb,p_revision integer) returns integer
language plpgsql security definer set search_path='' as $$
declare old public.product_inventory%rowtype;new_revision integer;
begin
 if not public.oc_has_role(array['admin','product_editor']) then raise exception 'Product editor access required' using errcode='42501';end if;
 if jsonb_typeof(p_values) is distinct from 'object' then raise exception 'Invalid stock values' using errcode='22023';end if;
 perform pg_advisory_xact_lock(hashtextextended('inventory:'||p_product_id::text,0));
 select * into old from public.product_inventory where product_id=p_product_id for update;
 if found then
  if p_revision<>old.revision then raise exception 'Stock changed in another session. Refresh and try again.' using errcode='40001';end if;
  new_revision:=old.revision+1;
 else
  if p_revision<>0 then raise exception 'Refresh this product before saving stock.' using errcode='40001';end if;
  new_revision:=1;
 end if;
 if coalesce(p_values->>'quantity','') !~ '^[0-9]{1,11}([.][0-9]{1,3})?$' or coalesce(p_values->>'reserved','') !~ '^[0-9]{1,11}([.][0-9]{1,3})?$' or coalesce(p_values->>'reorder_level','') !~ '^[0-9]{1,11}([.][0-9]{1,3})?$' then raise exception 'Stock quantities must be non-negative with up to 3 decimals' using errcode='22023';end if;
 if p_values->>'purchase_cost' is not null and p_values->>'purchase_cost' !~ '^[0-9]{1,12}([.][0-9]{1,2})?$' then raise exception 'Invalid purchase cost' using errcode='22023';end if;
 if p_revision is null or (p_values->>'quantity') is null or (p_values->>'reserved') is null or (p_values->>'reorder_level') is null then raise exception 'Quantity, reserved and reorder level are required' using errcode='22023';end if;
 insert into public.product_inventory(product_id,supplier_id,quantity,reserved,reorder_level,purchase_cost,bin_location,notes,revision)
 values(p_product_id,nullif(p_values->>'supplier_id','')::bigint,(p_values->>'quantity')::numeric,(p_values->>'reserved')::numeric,(p_values->>'reorder_level')::numeric,nullif(p_values->>'purchase_cost','')::numeric,left(p_values->>'bin_location',160),left(p_values->>'notes',10000),new_revision)
 on conflict(product_id) do update set supplier_id=excluded.supplier_id,quantity=excluded.quantity,reserved=excluded.reserved,reorder_level=excluded.reorder_level,purchase_cost=excluded.purchase_cost,bin_location=excluded.bin_location,notes=excluded.notes,revision=excluded.revision,updated_at=now();
 insert into public.smart_audit(entity,record_id,action,details,created_by) values('inventory',p_product_id::text,'stock_saved',jsonb_build_object('before',to_jsonb(old),'after',p_values),auth.uid());
 return new_revision;
end $$;
