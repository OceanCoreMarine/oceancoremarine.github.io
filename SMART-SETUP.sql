 insert into public.smart_audit(entity,record_id,action,details,created_by) values('team',p_user_id::text,'role_changed',jsonb_build_object('role',p_role),auth.uid());
end $$;

-- Basket snapshot is created on the server; visitor-supplied names/prices are ignored.
create or replace function public.oc_submit_enquiry(p_request jsonb,p_items jsonb,p_token uuid) returns text
language plpgsql security definer set search_path='' as $$
declare v_id text;item jsonb;p record;items jsonb:='[]'::jsonb;qty integer;first_item jsonb;req jsonb;seen bigint[]:='{}';
begin
 if p_token is null or jsonb_typeof(p_request) is distinct from 'object' or jsonb_typeof(p_items) is distinct from 'array' or jsonb_array_length(p_items) not between 1 and 50 then raise exception 'Invalid enquiry' using errcode='22023';end if;
 perform pg_advisory_xact_lock(hashtextextended(p_token::text,0));
 select id::text into v_id from public.quote_requests where basket_client_token=p_token;
 if found then return v_id;end if;
 for item in select value from jsonb_array_elements(p_items) loop
  if coalesce(item->>'product_id','') !~ '^[0-9]{1,15}$' or coalesce(item->>'quantity','') !~ '^[0-9]{1,7}$' then raise exception 'Invalid item or quantity' using errcode='22023';end if;
  qty:=(item->>'quantity')::integer;if qty not between 1 and 1000000 then raise exception 'Quantity must be 1 to 1000000' using errcode='22023';end if;
  if (item->>'product_id')::bigint=any(seen) then raise exception 'Duplicate basket product' using errcode='22023';end if;
  seen:=array_append(seen,(item->>'product_id')::bigint);
  select pr.id,pr.product_name,pr.part_number,pr.price,b.name as brand_name into p from public.products pr left join public.brands b on b.id=pr.brand_id where pr.id=(item->>'product_id')::bigint and pr.active=true;
  if not found then raise exception 'A product is no longer available; remove it from the basket' using errcode='22023';end if;
  items:=items||jsonb_build_array(jsonb_build_object('product_id',p.id,'product_name',p.product_name,'part_number',p.part_number,'brand_name',p.brand_name,'quantity',qty,'listed_price',p.price));
 end loop;
 first_item:=items->0;req:=p_request||jsonb_build_object('product_name',left(first_item->>'product_name',460)||case when jsonb_array_length(items)>1 then ' (+'||(jsonb_array_length(items)-1)::text||' more products)' else '' end,'part_number',first_item->>'part_number','quantity',first_item->'quantity');
 -- Reuse existing length/email checks and notification-compatible quote row creation.
 v_id:=public.submit_quote_request(req);
 update public.quote_requests set request_items=items,basket_client_token=p_token where id::text=v_id;
 return v_id;
end $$;

create or replace function public.oc_enquiry_to_quotation(p_id text,p_prices jsonb,p_customer_id bigint default null) returns jsonb
language plpgsql security definer set search_path='' as $$
declare q public.quote_requests%rowtype;items jsonb;row jsonb;price_row jsonb;calc jsonb;prepared jsonb:='[]';customer bigint;matches integer;quote_id bigint;num text;position integer:=0;unit_price numeric;product_id bigint;brand_name text;
begin
 if not public.oc_has_role(array['admin','sales']) then raise exception 'Sales access required' using errcode='42501';end if;
 select * into q from public.quote_requests where id::text=p_id for update;
 if not found then raise exception 'Enquiry not found' using errcode='22023';end if;
 if q.linked_quotation_id is not null then return jsonb_build_object('id',q.linked_quotation_id,'existing',true);end if;
 items:=q.request_items;
 if jsonb_array_length(items)=0 then
  if nullif(btrim(q.product_name),'') is null then raise exception 'Add a product in a manual quotation for this enquiry' using errcode='22023';end if;
  items:=jsonb_build_array(jsonb_build_object('product_id',null,'product_name',q.product_name,'part_number',q.part_number,'quantity',coalesce(q.quantity,1)));
 end if;
 if jsonb_typeof(p_prices) is distinct from 'array' or jsonb_array_length(p_prices)<>jsonb_array_length(items) then raise exception 'Enter a price for every line' using errcode='22023';end if;
 for row in select value from jsonb_array_elements(items) loop
  price_row:=p_prices->position;
  if coalesce(price_row->>'unit_price','') !~ '^[0-9]{1,10}([.][0-9]{1,2})?$' then raise exception 'Enter valid AED prices with up to 2 decimal places' using errcode='22023';end if;
  unit_price:=(price_row->>'unit_price')::numeric;
  if unit_price<=0 then raise exception 'Confirm a positive selling price for every item' using errcode='22023';end if;
  product_id:=nullif(row->>'product_id','')::bigint;
  if product_id is not null and not exists(select 1 from public.products where id=product_id) then product_id:=null;end if;
  prepared:=prepared||jsonb_build_array(jsonb_build_object('product_id',product_id,'product_name',row->>'product_name','part_number',row->>'part_number','brand_name',row->>'brand_name','quantity',row->'quantity','unit_price',unit_price,'discount',0));
  position:=position+1;
 end loop;
 calc:=public.oc_billing_totals(prepared,0,5);
 customer:=p_customer_id;
 if customer is not null then
  if not exists(select 1 from public.customers where id=customer) then raise exception 'Customer not found' using errcode='22023';end if;
 else
  select count(*),min(id) into matches,customer from public.customers where lower(email)=lower(q.email);
  if matches>1 then raise exception 'Several customers share this email; select the correct customer' using errcode='22023';end if;
  if matches=0 then insert into public.customers(company_name,contact_name,email,phone) values(q.company_name,q.customer_name,q.email,q.phone) returning id into customer;end if;
 end if;
 num:=public.next_quotation_number();
 insert into public.quotations(quotation_number,customer_id,quotation_date,valid_until,subtotal,discount,other_charges,vat_rate,vat_amount,grand_total,payment_type,delivery_terms,notes,created_by)
 values(num,customer,current_date,current_date+15,(calc->>'subtotal')::numeric,(calc->>'discount')::numeric,0,5,(calc->>'vat_amount')::numeric,(calc->>'grand_total')::numeric,'To be confirmed','',q.message,auth.uid()) returning id into quote_id;
 for row in select value from jsonb_array_elements(prepared) loop
  insert into public.quotation_items(quotation_id,product_id,product_name,part_number,brand_name,quantity,unit_price,discount,line_total)
  values(quote_id,nullif(row->>'product_id','')::bigint,row->>'product_name',row->>'part_number',row->>'brand_name',(row->>'quantity')::numeric,(row->>'unit_price')::numeric,0,round((row->>'quantity')::numeric*(row->>'unit_price')::numeric,2));
 end loop;
 update public.quote_requests set linked_quotation_id=quote_id,sales_stage='Quoted' where id=q.id;
 insert into public.smart_audit(entity,record_id,action,details,created_by) values('enquiry',p_id,'quotation_created',jsonb_build_object('quotation_id',quote_id),auth.uid());
 return jsonb_build_object('id',quote_id,'number',num,'existing',false);
end $$;

create or replace function public.oc_bulk_update_products(p_rows jsonb) returns integer language plpgsql security definer set search_path='' as $$
declare row jsonb;p public.products%rowtype;count_updated integer:=0;seen bigint[]:='{}';v_price numeric;v_brand bigint;v_status text;
begin
 if not public.oc_has_role(array['admin','product_editor']) then raise exception 'Product editor access required' using errcode='42501';end if;
 if jsonb_typeof(p_rows) is distinct from 'array' or jsonb_array_length(p_rows) not between 1 and 200 then raise exception 'Select 1 to 200 products' using errcode='22023';end if;
 for row in select value from jsonb_array_elements(p_rows) loop
  if exists(select 1 from jsonb_object_keys(row) as keys(k) where k not in ('id','price','brand_id','active','featured','top_selling','stock_status')) then raise exception 'Unsupported bulk field' using errcode='22023';end if;
  if coalesce(row->>'id','') !~ '^[0-9]{1,15}$' then raise exception 'Invalid product ID' using errcode='22023';end if;
  if (row->>'id')::bigint=any(seen) then raise exception 'Duplicate product ID in batch' using errcode='22023';end if;
  seen:=array_append(seen,(row->>'id')::bigint);
  select * into p from public.products where id=(row->>'id')::bigint for update;
  if not found then raise exception 'Product % not found',row->>'id' using errcode='22023';end if;
  if row?'price' and row->'price'<>'null'::jsonb and coalesce(row->>'price','') !~ '^[0-9]{1,10}([.][0-9]{1,2})?$' then raise exception 'Invalid AED price' using errcode='22023';end if;
  if (row?'active' and jsonb_typeof(row->'active')<>'boolean') or (row?'featured' and jsonb_typeof(row->'featured')<>'boolean') or (row?'top_selling' and jsonb_typeof(row->'top_selling')<>'boolean') then raise exception 'Flags must be true or false' using errcode='22023';end if;
  v_price:=case when row?'price' then nullif(row->>'price','')::numeric else p.price end;
  if row?'brand_id' and row->'brand_id'<>'null'::jsonb and coalesce(row->>'brand_id','') !~ '^[0-9]{1,15}$' then raise exception 'Invalid brand ID' using errcode='22023';end if;
  v_brand:=case when row?'brand_id' then nullif(row->>'brand_id','')::bigint else p.brand_id end;
  if v_brand is not null and not exists(select 1 from public.brands where id=v_brand) then raise exception 'Brand does not exist' using errcode='22023';end if;
  if row?'stock_status' then
   v_status:=row->>'stock_status';if v_status not in ('In stock','On order','Out of stock','Request availability') or v_status is null then raise exception 'Invalid stock status' using errcode='22023';end if;
   insert into public.product_details(product_id,stock_status) values(p.id,v_status) on conflict(product_id) do update set stock_status=excluded.stock_status,updated_at=now();
  end if;
  update public.products set price=v_price,brand_id=v_brand,
   active=case when row?'active' then (row->>'active')::boolean else p.active end,
   featured=case when row?'featured' then (row->>'featured')::boolean else p.featured end,
   top_selling=case when row?'top_selling' then (row->>'top_selling')::boolean else p.top_selling end,updated_at=now() where id=p.id;
  insert into public.smart_audit(entity,record_id,action,details,created_by) values('product',p.id::text,'bulk_update',row-'id',auth.uid());
  count_updated:=count_updated+1;
 end loop;
 return count_updated;
end $$;

create or replace function public.oc_track_event(p_event text,p_product_id bigint default 0,p_term text default '') returns void
language plpgsql security definer set search_path='' as $$
declare v_term text:=lower(left(btrim(coalesce(p_term,'')),100));
begin
 if not exists(select 1 from public.site_content where key='website' and content->>'analytics_enabled'='true') then return;end if;
 if p_event not in ('product_view','search','no_results','quote_click','whatsapp') then return;end if;
 if v_term like '%@%' or v_term ~ '[+][0-9]' then return;end if;
 if p_event not in ('search','no_results') then v_term:='';end if;
 if p_event in ('search','no_results') and length(v_term)<2 then return;end if;
 if p_product_id is null or (p_product_id<>0 and not exists(select 1 from public.products where id=p_product_id and active=true)) then return;end if;
 -- Only aggregate counters: no customer email, user ID, IP, cookie or session ID is stored.
 insert into public.smart_metrics(day,event,product_id,term,count) values(current_date,p_event,p_product_id,v_term,1)
 on conflict(day,event,product_id,term) do update set count=public.smart_metrics.count+1;
end $$;

