-- Run once in the OceanCore Supabase SQL Editor.
-- Supports manually curated Top Selling items and published customer reviews.

alter table public.products
  add column if not exists top_selling boolean not null default false;

alter table public.quote_requests
  add column if not exists notification_status text not null default 'pending',
  add column if not exists notification_sent_at timestamptz;

create table if not exists public.customer_reviews (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  company_name text,
  review_text text not null,
  rating smallint not null default 5 check (rating between 1 and 5),
  is_published boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.customer_reviews enable row level security;

drop policy if exists "Public can view published customer reviews" on public.customer_reviews;
create policy "Public can view published customer reviews"
  on public.customer_reviews for select to anon, authenticated
  using (is_published = true);

drop policy if exists "Admins manage customer reviews" on public.customer_reviews;
create policy "Admins manage customer reviews"
  on public.customer_reviews for all to authenticated
  using (exists (
    select 1 from public.admin_users
    where public.admin_users.user_id = auth.uid()
  ))
  with check (exists (
    select 1 from public.admin_users
    where public.admin_users.user_id = auth.uid()
  ));
