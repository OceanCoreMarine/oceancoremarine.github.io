-- Run in Supabase SQL Editor. Existing homepage customer_reviews are preserved.
create table if not exists public.product_reviews (
 id bigint generated by default as identity primary key,
 product_id bigint not null references public.products(id) on delete cascade,
 customer_name text not null check(char_length(btrim(customer_name)) between 2 and 100),
 company_name text check(char_length(company_name)<=120),
 review_text text not null check(char_length(btrim(review_text)) between 10 and 2000),
 rating smallint not null check(rating between 1 and 5),
 source text not null default 'customer' check(source in ('customer','admin_customer','oceancore_note')),
 is_published boolean not null default false,
 created_at timestamptz not null default now()
);
create index if not exists product_reviews_product_published_idx on public.product_reviews(product_id,is_published,created_at desc);
alter table public.product_reviews enable row level security;
grant select on public.product_reviews to anon,authenticated;
grant insert,update,delete on public.product_reviews to authenticated;
revoke insert on public.product_reviews from anon;
grant insert(product_id,customer_name,company_name,review_text,rating,source) on public.product_reviews to anon;
grant usage,select on sequence public.product_reviews_id_seq to anon,authenticated;
drop policy if exists "Published product reviews" on public.product_reviews;
create policy "Published product reviews" on public.product_reviews for select to anon,authenticated using(is_published=true);
drop policy if exists "Customers submit pending reviews" on public.product_reviews;
create policy "Customers submit pending reviews" on public.product_reviews for insert to anon,authenticated with check(
 is_published=false and source='customer' and exists(select 1 from public.products where products.id=product_reviews.product_id and products.active=true)
);
drop policy if exists "Admins manage product reviews" on public.product_reviews;
create policy "Admins manage product reviews" on public.product_reviews for all to authenticated
 using(exists(select 1 from public.admin_users where user_id=auth.uid()))
 with check(exists(select 1 from public.admin_users where user_id=auth.uid()));
